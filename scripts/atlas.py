#!/usr/bin/env python3
"""Build snippets/atlas.mdx, the framework map on the posture pages, from
the two pages it summarises: posture/security-policies.mdx, whose table
gives each policy's category and title, and posture/frameworks.mdx, whose
tables give each framework's controls and the policies that answer them.

Run it from the repository root after either page changes:

    python3 scripts/atlas.py

The categories' names, lines and links, and the frameworks' short labels,
are set here: neither page says them.
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
POLICIES = ROOT / "posture" / "security-policies.mdx"
FRAMEWORKS = ROOT / "posture" / "frameworks.mdx"
OUT = ROOT / "snippets" / "atlas.mdx"

# The frameworks, in the order frameworks.mdx gives them, by the start of
# each one's accordion title.
FRAMEWORK_SET = [
    ("owasp-llm", "OWASP LLM", "OWASP Top 10 for LLM Applications"),
    ("owasp-agentic", "OWASP Agentic", "OWASP Top 10 for Agentic Applications"),
    ("mitre-atlas", "MITRE ATLAS", "MITRE ATLAS"),
    ("nist-ai-rmf", "NIST AI RMF", "NIST AI Risk Management Framework"),
    ("iso-42001", "ISO 42001", "ISO/IEC 42001"),
    ("eu-ai-act", "EU AI Act", "EU AI Act"),
    ("aws-security-hub", "AWS Security Hub", "AWS Security Hub"),
]

# The categories, in the map's order: the name the policies table gives,
# a line saying what it covers, and the pages to read about it.
CATEGORIES = [
    ("gov", "Governance", "Shadow assets, owners and unused agents", [["Registry", "/govern/registry"], ["Shadow AI", "/discover/shadow-ai"]]),
    ("exp", "Exposure", "Who can reach an asset, and from where", [["Access and sharing", "/discover/asset-details#access-and-sharing"], ["AI inventory", "/discover/ai-inventory"]]),
    ("iam", "Identity and access", "Whose credentials an agent acts with", [["People and spend", "/discover/people-and-spend"], ["Access and sharing", "/discover/asset-details#access-and-sharing"]]),
    ("agy", "Agency", "What an agent can do on its own", [["Access and sharing", "/discover/asset-details#access-and-sharing"], ["Findings", "/posture/findings"]]),
    ("obs", "Observability", "Whether anyone traces and scores an agent", [["Observability", "/monitor/observability"], ["Evals", "/monitor/evals/get-started"]]),
    ("rt", "Runtime protection", "Whether calls pass a gateway or a guardrail", [["LLM gateway", "/llm-gateway/overview"], ["Guardrails", "/secure/guardrails/list"]]),
    ("dat", "Data and secrets", "Credentials in the open, and paths out", [["Findings", "/posture/findings"], ["Guardrails", "/secure/guardrails/list"]]),
    ("sup", "Supply chain", "Components from outside the registry", [["Registry", "/govern/registry"], ["Security policies", "/posture/security-policies"]]),
]

HEADER = "{/* Generated by scripts/atlas.py from posture/frameworks.mdx and posture/security-policies.mdx. Do not edit by hand. */}"

TEMPLATE = r"""
export const Atlas = () => (
  <div className="oc-atlas" data-fw="all">
    <div className="oc-atlas-head">
      <div className="oc-atlas-count">
        <span><b>{ATLAS.policies}</b> security policies</span>
        <span><b>{ATLAS.controls}</b> framework controls</span>
        <span><b>{ATLAS.frameworks.length}</b> frameworks</span>
      </div>
      <div className="oc-atlas-pick" role="group" aria-label="Show one framework's controls">
        <button type="button" data-fw-pick="all" aria-pressed="true">All</button>
        {ATLAS.frameworks.map((f) => (
          <button type="button" key={f.id} data-fw-pick={f.id} aria-pressed="false">{f.label}</button>
        ))}
      </div>
    </div>
    <div className="oc-atlas-scroll">
      <table className="oc-atlas-grid">
        <thead>
          <tr>
            <th scope="col" className="oc-atlas-corner"><span className="oc-sr">Category</span></th>
            {ATLAS.frameworks.map((f) => (
              <th scope="col" key={f.id} data-fw-col={f.id}>{f.label}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          {ATLAS.categories.map((c) => (
            <tr key={c.id} className={"oc-cat-" + c.id}>
              <th scope="row">
                <a className="oc-atlas-cat" href={c.pages[0][1]} title={c.line}><i aria-hidden="true" />{c.name}<svg className="oc-go" viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12h14M13 6l6 6-6 6" /></svg></a>
              </th>
              {ATLAS.frameworks.map((f) => (
                <td key={f.id} data-fw-col={f.id}>
                  {c.cells[f.id].length ? (
                    <span className="oc-cell" title={c.cells[f.id].map((it) => it.code + " " + it.name).join("\n")}>
                      <span className="oc-n" data-n={Math.min(c.cells[f.id].length, 4)}>{c.cells[f.id].length}</span>
                      <span className="oc-codes">
                        {c.cells[f.id].map((it) => (
                          <span key={it.code} className="oc-ctl">{it.code.replace("BedrockAgentCore", "AgentCore")}</span>
                        ))}
                      </span>
                    </span>
                  ) : (
                    <span className="oc-ctl-none" aria-label="None">·</span>
                  )}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
    <p className="oc-atlas-note">Each number counts the framework's controls that a category's policies answer. Pick a framework to see them.</p>
  </div>
);
"""


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def policies():
    """Each policy row: its id, title and category, in the table's order."""
    out = []
    for line in POLICIES.read_text().splitlines():
        if re.match(r"^\| [A-Z]+-\d+ \|", line):
            c = cells(line)
            out.append({"id": c[0], "title": c[1], "category": c[2]})
    return out


def code_and_name(item):
    """A control's code and name: its first word, or its first two when the
    first has no digit (GOVERN 1.7, Art. 26), then the rest."""
    words = item.split(" ")
    n = 1 if re.search(r"\d", words[0]) else 2
    return " ".join(words[:n]), " ".join(words[n:])


def frameworks():
    """Each framework's controls: code, name and the policies answering it."""
    text = FRAMEWORKS.read_text()
    out = {}
    for fid, _, title in FRAMEWORK_SET:
        start = text.index('<Accordion title="' + title)
        body = text[start:text.index("</Accordion>", start)]
        rows = []
        for line in body.splitlines()[1:]:
            if not line.startswith("| ") or line.startswith("|---"):
                continue
            c = cells(line)
            if c[1] == "Policies":
                continue
            code, name = code_and_name(c[0])
            rows.append({"code": code, "name": name, "policies": [p.strip() for p in c[1].split(",")]})
        out[fid] = rows
    return out


def atlas():
    pols, fws = policies(), frameworks()
    categories = []
    for cid, name, line, pages in CATEGORIES:
        mine = [p for p in pols if p["category"] == name]
        ids = {p["id"] for p in mine}
        categories.append({
            "id": cid, "name": name, "line": line, "pages": pages,
            "policies": [{"id": p["id"], "title": p["title"]} for p in mine],
            "cells": {fid: [{"code": r["code"], "name": r["name"], "policies": [p for p in r["policies"] if p in ids]}
                            for r in fws[fid] if any(p in ids for p in r["policies"])]
                      for fid, _, _ in FRAMEWORK_SET},
        })
    return {
        "frameworks": [{"id": fid, "label": label, "count": len(fws[fid])} for fid, label, _ in FRAMEWORK_SET],
        "categories": categories,
        "policies": len(pols),
        "controls": sum(len(fws[fid]) for fid, _, _ in FRAMEWORK_SET),
    }


def main():
    data = json.dumps(atlas(), separators=(",", ":"), ensure_ascii=False)
    OUT.write_text(HEADER + "\n\nexport const ATLAS = " + data + ";\n" + TEMPLATE)


if __name__ == "__main__":
    main()
